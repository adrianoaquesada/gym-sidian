import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";

const banner =
`/*
GENERATED BY ESBUILD — no editar main.js a mano.
Fuente TypeScript en src/. Compilar con:  npm run build   (o npm run dev en watch)
*/
`;

const args = process.argv.slice(2);
const prod = args[0] === "production";

const context = await esbuild.context({
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
        "obsidian",
        "electron",
        "@codemirror/autocomplete",
        "@codemirror/collab",
        "@codemirror/commands",
        "@codemirror/language",
        "@codemirror/lint",
        "@codemirror/search",
        "@codemirror/state",
        "@codemirror/view",
        "@lezer/common",
        "@lezer/highlight",
        "@lezer/lr",
        ...builtinModules,
    ],
    format: "cjs",
    target: "es2020",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile: "main.js",
    banner: { js: banner },
});

if (prod) {
    await context.rebuild();
    process.exit(0);
} else {
    await context.watch();
}
